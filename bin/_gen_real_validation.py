#!/usr/bin/env python3
"""Generate real_validation.sh script."""
import os

lines = [
    '#!/usr/bin/env bash',
    'set -o pipefail',
    '',
    '# Initialize conda for non-interactive shell',
    'eval "$(conda shell.bash hook)"',
    'conda activate DAY-EC',
    '',
    'ANALYSIS_DIR="/fsx/analysis_results/ubuntu/validate-extensions-20260323/daylily-omics-analysis"',
    'LOG_DIR="/tmp/val_logs"',
    'mkdir -p "$LOG_DIR"',
    '',
    'cd "$ANALYSIS_DIR" || { echo "FATAL: cannot cd to $ANALYSIS_DIR"; exit 1; }',
    '',
    'echo "=== Starting real validation $(date) ==="',
    '',
    '# Backup original units.tsv',
    'cp config/units.tsv config/units.tsv.bak.real',
    'echo "Backed up units.tsv to units.tsv.bak.real"',
    '',
    'echo ""',
    'echo "##############################"',
    'echo "# PHASE 1: New Feature Targets"',
    'echo "##############################"',
    '',
    '# Create subset: header + R0 (SR1x-LR1x) + R1 (SR1x-LR3x)',
    'head -1 config/units.tsv.bak.real > config/units.tsv',
    'sed -n 2p config/units.tsv.bak.real >> config/units.tsv',
    'sed -n 3p config/units.tsv.bak.real >> config/units.tsv',
    'echo "Phase 1 subset: $(wc -l < config/units.tsv) lines (header + 2 units)"',
    'echo "Unit RUNIDs:"',
    'tail -n +2 config/units.tsv | cut -f1-3',
    '',
    '# Initialize and activate',
    'source dyoainit --project daylily-global',
    'source bin/day_activate slurm hg38_broad',
    '',
    '# Run all Phase 1 targets in one snakemake call (shared upstream steps)',
    'echo "--- Starting Phase 1 targets $(date) ---"',
    'bash bin/day_run produce_sentdhiomr_cnv produce_sentdhiomr_segdup produce_sentdhiomr_mito produce_manta -p -j 2 -k -T 1 2>&1 | tee "$LOG_DIR/real_phase1_all.log"',
    'rc=${PIPESTATUS[0]}',
    'echo "RETURN CODE for Phase 1: $rc" | tee -a "$LOG_DIR/real_phase1_all.log"',
    'echo "--- Finished Phase 1 $(date) ---"',
    '',
    'echo ""',
    'echo "##############################"',
    'echo "# PHASE 2: SR Pipeline Regression"',
    'echo "##############################"',
    '',
    '# Create subset: header + first 30x SR unit',
    'head -1 config/units.tsv.bak.real > config/units.tsv',
    'grep -m1 SR30x config/units.tsv.bak.real >> config/units.tsv',
    'echo "Phase 2 subset: $(wc -l < config/units.tsv) lines (header + 1 unit)"',
    'echo "Unit RUNIDs:"',
    'tail -n +2 config/units.tsv | cut -f1-3',
    '',
    '# Run standard SR pipeline: alignment + dedup + SNV calling + concordance + SV callers',
    'echo "--- Starting Phase 2 SR pipeline $(date) ---"',
    'bash bin/day_run produce_sent_align produce_dmd_dedup_cram produce_sentd_snv_vcf produce_manta_sv_vcf produce_tiddit_sv_vcf produce_snv_concordances -p -j 2 -k -T 1 2>&1 | tee "$LOG_DIR/real_phase2_sr.log"',
    'rc=${PIPESTATUS[0]}',
    'echo "RETURN CODE for Phase 2: $rc" | tee -a "$LOG_DIR/real_phase2_sr.log"',
    'echo "--- Finished Phase 2 $(date) ---"',
    '',
    '# Restore',
    'cp config/units.tsv.bak.real config/units.tsv',
    'echo ""',
    'echo "=== Restored original units.tsv ==="',
    'echo "=== All validation complete $(date) ==="',
    'echo ""',
    'echo "=== SUMMARY ==="',
    'echo "Phase 1 log: $LOG_DIR/real_phase1_all.log"',
    'echo "Phase 2 log: $LOG_DIR/real_phase2_sr.log"',
    'grep "RETURN CODE" $LOG_DIR/real_phase*.log 2>/dev/null || echo "No return codes found"',
]

out = '/tmp/real_validation.sh'
with open(out, 'w') as f:
    f.write('\n'.join(lines) + '\n')
os.chmod(out, 0o755)
print(f'Written {len(lines)} lines to {out}')
